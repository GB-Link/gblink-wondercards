// Project Wonder distributions: what each patched Aurora Ticket distribution
// cartridge ("JPAJ - *.bps") sends to English Emerald and FireRed/LeafGreen.
// The egg events hold one payload per species.
function decodeBase64(s) {
  const bin = atob(s.replace(/\s+/g, ""));
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

