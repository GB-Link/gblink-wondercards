#!/usr/bin/env node
/**
 * Re-assemble Thumb templates into src/dailyred/rom/thumb-templates.js.
 * Requires arm-none-eabi-as / objcopy / nm.
 *
 *   node tools/dailyred/bake-templates.mjs
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { forRom, ROMS } from '../../src/dailyred/rom/symbols.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const asm = join(__dirname, 'dailyred_battle.s');
const OUT = join(__dirname, '../../src/dailyred/rom/thumb-templates.js');
const DEFSYMS = [
  'PARTY', 'PARTY_COUNT', 'ENEMY_PARTY', 'CREATE_MON', 'SET_MON_DATA',
  'SET_MON_MOVE_SLOT', 'CALCULATE_STATS', 'BATTLE_TYPE', 'TRAINER_BATTLE_OPPONENT_A',
  'MAIN', 'TASKS', 'CREATE_TASK', 'SET_MAIN_CALLBACK2', 'PLAY_MAP_BGM',
  'BATTLE_TRANSITION_START', 'IS_BATTLE_TRANSITION_DONE', 'CLEANUP_OVERWORLD',
  'CB2_INIT_BATTLE', 'SCRIPT_CONTEXT_STOP', 'CB2_RETURN', 'CLOSE_LINK',
  'TRAINER_OPPONENT_ID', 'MUS_BATTLE',
];

function bake(romId) {
  const symbols = forRom(romId);
  const dir = mkdtempSync(join(tmpdir(), 'dailyred-bake-'));
  const obj = join(dir, 'payload.o');
  const bin = join(dir, 'payload.bin');
  const args = ['-mthumb', '-mcpu=arm7tdmi'];
  for (const name of DEFSYMS) {
    args.push('--defsym', `${name}=0x${(Number(symbols[name] ?? 0) >>> 0).toString(16).toUpperCase()}`);
  }
  args.push('-o', obj, asm);
  execFileSync('arm-none-eabi-as', args);
  execFileSync('arm-none-eabi-objcopy', ['-O', 'binary', obj, bin]);
  const nm = execFileSync('arm-none-eabi-nm', [obj], { encoding: 'utf8' });
  const m = nm.match(/^([0-9a-fA-F]+)\s+[A-Za-z]\s+mon_table$/m);
  if (!m) throw new Error('mon_table missing');
  const monTableAt = parseInt(m[1], 16);
  const bytes = readFileSync(bin);
  bytes.fill(0, monTableAt, monTableAt + 12 * 22);
  rmSync(dir, { recursive: true, force: true });
  return { rom: romId, monTableAt, bytes: bytes.toString('base64') };
}

const templates = ROMS.map(bake);
const out = `/** Pre-assembled Thumb payloads (mon_table zeroed). Regenerated by tools/dailyred/bake-templates.mjs */\nexport const THUMB_TEMPLATES = ${JSON.stringify(templates, null, 2)};\n`;
writeFileSync(OUT, out);
for (const t of templates) {
  console.log(`${t.rom} table@${t.monTableAt} len=${Buffer.from(t.bytes, 'base64').length}`);
}
